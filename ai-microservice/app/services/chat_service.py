
"""
Chat service for generating responses using the configured local LLM.

The service coordinates chat requests and delegates model inference
to the Ollama client.
"""

from app.clients.ollama_client import generate_ollama_response


async def generate_chat_response(message: str) -> str:
    """
    Generate a response for a user's chat message.

    Args:
        message: The user's input message.

    Returns:
        The response generated by the configured local model.
    """
    return await generate_ollama_response(message)
