
"""
Client for communicating with the locally running Ollama service.

Ollama performs inference on the local machine. The model name and
base URL are read from application settings, not hardcoded here.
"""

import httpx
from fastapi import HTTPException, status

from app.config import settings


async def generate_ollama_response(message: str) -> str:
    """
    Send a prompt to Ollama and return the generated response.

    Args:
        message: The user's input message.

    Returns:
        The text generated by the configured Ollama model.

    Raises:
        HTTPException: If Ollama is unavailable or returns an invalid response.
    """
    # Local model inference may take longer on a machine with limited RAM.
    timeout = httpx.Timeout(120.0, connect=5.0)

    payload = {
        "model": settings.ollama_model,
        "prompt": message,
        "stream": False,
    }

    try:
        async with httpx.AsyncClient(
            base_url=settings.ollama_base_url,
            timeout=timeout,
        ) as client:
            response = await client.post(
                "/api/generate",
                json=payload,
            )
            response.raise_for_status()

            result = response.json()
            generated_text = result.get("response")

            if not isinstance(generated_text, str) or not generated_text.strip():
                raise HTTPException(
                    status_code=status.HTTP_502_BAD_GATEWAY,
                    detail="Ollama returned an empty or invalid response.",
                )

            return generated_text.strip()

    except httpx.TimeoutException as exc:
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail="Ollama took too long to generate a response.",
        ) from exc

    except httpx.ConnectError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "Ollama is unavailable. Ensure Ollama is running "
                "and the configured base URL is correct."
            ),
        ) from exc

    except httpx.HTTPStatusError as exc:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="Ollama returned an unsuccessful HTTP response.",
        ) from exc
