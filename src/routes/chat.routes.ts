
/**
 * Chat Routes
 *
 * Responsibilities:
 * - Define the HTTP routes for chat operations.
 * - Validate requests before they reach the controller.
 * - Document the endpoint through OpenAPI annotations.
 *
 * Endpoint:
 * POST /api/v1/chat
 */

/**
 * @openapi
 * components:
 *   schemas:
 *     ChatRequest:
 *       type: object
 *       required:
 *         - message
 *       properties:
 *         message:
 *           type: string
 *           minLength: 1
 *           maxLength: 2000
 *           example: Explain what a REST API is.
 *     ChatResult:
 *       type: object
 *       properties:
 *         message:
 *           type: string
 *           description: Response generated by the configured AI model.
 *         provider:
 *           type: string
 *           example: ollama
 *
 * /chat:
 *   post:
 *     tags:
 *       - Chat
 *     summary: Generate a response using the local AI model
 *     security:
 *       - BearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             $ref: '#/components/schemas/ChatRequest'
 *     responses:
 *       '200':
 *         description: Chat response generated successfully
 *       '400':
 *         description: Invalid request
 *       '502':
 *         description: AI service returned an unsuccessful response
 *       '503':
 *         description: AI service is unavailable
 *       '504':
 *         description: AI inference timed out
 */

import { Router } from "express";

import { chat } from "../controllers/chat.controller.js";
import validate from "../middlewares/validate.middleware.js";
import authenticate from "../middlewares/auth.middleware.js";
import { chatRequestSchema } from "../validations/chat.validation.js";

/** Router for chat endpoints. */
const router = Router();

/**
 * POST /
 *
 * Validates the message and passes the request to the chat controller.
 * The full path is /api/v1/chat when mounted in app.ts.
 */
router.post(
    "/",
    authenticate,
    validate(chatRequestSchema),
    chat,
);

export default router;
