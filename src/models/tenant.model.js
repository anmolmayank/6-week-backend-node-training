/**
 * ============================================================================
 * Tenant Model
 * ============================================================================
 *
 * Purpose
 * -------
 * Defines the MongoDB schema for Tenant documents.
 *
 * Responsibilities
 * ----------------
 * - Defines Tenant structure.
 * - Defines Rental Agreement metadata.
 * - Applies database-level validations.
 * - Enables automatic timestamps.
 *
 * Notes
 * -----
 * - Only metadata of uploaded PDFs is stored in MongoDB.
 * - Actual PDF files are stored on the local file system.
 *
 * ============================================================================
 */

import mongoose from "mongoose";

const { Schema, model } = mongoose;

/**
 * ============================================================================
 * Rental Agreement Schema
 * ============================================================================
 *
 * Represents metadata of the uploaded rental agreement.
 *
 * The PDF itself is stored inside:
 *
 * uploads/agreements
 *
 * MongoDB stores only metadata.
 *
 * ============================================================================
 */
const RentalAgreementSchema = new Schema(
  {
    originalName: {
      type: String,

      // Original filename uploaded by the user.
      required: true,

      trim: true,

      maxlength: 255,
    },

    storedName: {
      type: String,

      // UUID generated filename stored on disk.
      required: true,

      trim: true,

      maxlength: 255,
    },

    mimeType: {
      type: String,

      required: true,

      trim: true,

      maxlength: 100,
    },

    size: {
      type: Number,

      // File size in bytes.
      required: true,

      min: 0,
    },

    uploadedAt: {
      type: Date,

      // Automatically populated during upload.
      default: Date.now,
    },
  },
  {
    // Embedded documents don't require their own ObjectId.
    _id: false,
  },
);

/**
 * ============================================================================
 * Tenant Schema
 * ============================================================================
 */
const TenantSchema = new Schema(
  {
    tenantName: {
      type: String,

      required: true,

      // Removes accidental leading/trailing spaces.
      trim: true,

      maxlength: 100,
    },

    apartmentNumber: {
      type: String,

      required: true,

      trim: true,

      // One apartment can have only one active tenant.
      unique: true,

      maxlength: 20,
    },

    /**
     * Monthly rent amount.
     */
    monthlyRent: {
      type: Number,
      required: true,
      min: 0,
    },

    /**
     * Rental agreement metadata.
     *
     * Stores only file metadata.
     * The actual PDF is stored on the filesystem.
     */
    rentalAgreement: {
      /**
       * Original filename uploaded by the user.
       */
      originalName: {
        type: String,
        trim: true,
      },

      /**
       * Filename generated by the server.
       */
      storedName: {
        type: String,
        trim: true,
      },

      /**
       * MIME type of the uploaded file.
       */
      mimeType: {
        type: String,
        trim: true,
      },

      /**
       * File size in bytes.
       */
      size: {
        type: Number,
      },

      /**
       * Relative path of the stored file.
       */
      path: {
        type: String,
        trim: true,
      },

      /**
       * Upload timestamp.
       */
      uploadedAt: {
        type: Date,
      },
    },
  },
  {
    // Automatically manages createdAt & updatedAt.
    timestamps: true,
  },
);

const TenantModel = model("Tenant", TenantSchema);

export default TenantModel;

/**
 * ============================================================================
 * Learning Notes
 * ============================================================================
 *
 * 1. Why embedded schema?
 *    One tenant owns exactly one rental agreement.
 *
 * 2. Why _id:false?
 *    Embedded documents don't require separate identities.
 *
 * 3. Why timestamps?
 *    Mongoose automatically maintains createdAt & updatedAt.
 *
 * ============================================================================
 */
